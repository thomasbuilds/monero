TEST(difficulty, asert_monotonic)
{
  const uint64_t anchor_time = 1700000000, blocks = 100000, half_life = DIFFICULTY_ASERT_HALF_LIFE;
  const uint64_t on_schedule = anchor_time + DIFFICULTY_TARGET_V2 * blocks;
  for (const cryptonote::difficulty_type &anchor: {MKDIFF(0, 1), MKDIFF(0, 1000), MKDIFF(0, 600000000000), MKDIFF(1, 1), MKDIFF(0xffffffffffffffff, 0xffffffffffffffff)})
  {
    ASSERT_EQ(cryptonote::next_difficulty_asert(anchor, anchor_time, on_schedule, blocks, DIFFICULTY_TARGET_V2, half_life), anchor);
    cryptonote::difficulty_type prev = cryptonote::next_difficulty_asert(anchor, anchor_time, on_schedule - 3 * half_life - 1, blocks, DIFFICULTY_TARGET_V2, half_life);
    for (uint64_t time = on_schedule - 3 * half_life; time <= on_schedule + 3 * half_life; ++time)
    {
      const cryptonote::difficulty_type d = cryptonote::next_difficulty_asert(anchor, anchor_time, time, blocks, DIFFICULTY_TARGET_V2, half_life);
      ASSERT_LE(d, prev) << anchor << " " << time;
      ASSERT_GE(d, 1);
      prev = d;
    }
    ASSERT_LT(prev, anchor == 1 ? 2 : anchor);
  }
}
